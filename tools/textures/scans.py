"""LUMIERE v14 - the scanned props' textures into the engine's texture arrays (tools/blender/scans14.py wrote OUT/scans.json).
Per material: albedo x ambient occlusion (the ARM map's red channel: folds and seams stay dark under the engine's per-vertex light)
-> www/tex/<mat>_a.jpg, the OpenGL normal map -> <mat>_n.jpg, roughness (ARM green) -> <mat>_r.jpg (the arrays carry it in the albedo's
alpha), all 512 px (the arrays' size on Medium and High). Metalness is one number per material (the mean of ARM blue where the surface
is metal). Glass (alpha BLEND) maps to the library's glass; alpha-tested leaves keep a PNG with alpha for the foliage shader.
Writes www/js/scans.js: SCAN_LIB (library entries from id 48 up) and SCAN_NAMED (material name -> id, tint).

    python3 -I tools/textures/scans.py OUT/scans.json www
"""
import json, os, sys
from PIL import Image, ImageChops
import numpy as np

meta = json.load(open(sys.argv[1])); www = sys.argv[2]; S = 512
tex_dir = os.path.join(www, 'tex'); os.makedirs(tex_dir, exist_ok=True)
lib, named, rows, nid = {}, {}, [], 48


def load(p, mode):
    return Image.open(p).convert(mode).resize((S, S), Image.LANCZOS)


for name, m in meta.items():
    for mt in m['materials']:
        mat, alpha = mt['mat'], mt.get('alpha', 'OPAQUE')
        if alpha == 'BLEND':                       # glass: the library's own glass (drawn see-through in the lobby)
            named[mat] = [10, '#2a3036']; rows.append((mat, 'glass')); continue
        base = load(mt['base'], 'RGBA') if mt.get('base') else Image.new('RGBA', (S, S), (200, 200, 200, 255))
        arm = load(mt['arm'], 'RGB') if mt.get('arm') else None
        a = np.asarray(base).astype(np.float32) / 255.0
        col = np.array(mt.get('color', [1, 1, 1, 1])[:3], np.float32); a[..., :3] *= col
        if arm is not None and 'rough' not in os.path.basename(mt['arm']):
            ar = np.asarray(arm).astype(np.float32) / 255.0; ao, rough, metal = ar[..., 0], ar[..., 1], ar[..., 2]
        else:
            ao = np.ones((S, S), np.float32); rough = (np.asarray(arm.convert('L')).astype(np.float32) / 255.0) if arm is not None else np.full((S, S), 0.6, np.float32)
            metal = np.full((S, S), float(mt.get('metal', 0)), np.float32)
        a[..., :3] *= (0.3 + 0.7 * ao[..., None]) ** 1.0     # the scan's occlusion in its colour
        rgb = Image.fromarray(np.clip(a[..., :3] * 255, 0, 255).astype(np.uint8), 'RGB')
        leaf = alpha == 'MASK'
        if leaf:
            rgba = Image.fromarray(np.clip(np.dstack([a[..., :3], a[..., 3]]) * 255, 0, 255).astype(np.uint8), 'RGBA'); rgba.save(os.path.join(tex_dir, mat + '_a.png'), optimize=True)
        rgb.save(os.path.join(tex_dir, mat + '_a.jpg'), quality=88)
        if mt.get('normal'): load(mt['normal'], 'RGB').save(os.path.join(tex_dir, mat + '_n.jpg'), quality=90)
        else: Image.new('RGB', (S, S), (128, 128, 255)).save(os.path.join(tex_dir, mat + '_n.jpg'), quality=90)
        Image.fromarray(np.clip(rough * float(mt.get('rough', 1)) * 255, 0, 255).astype(np.uint8), 'L').save(os.path.join(tex_dir, mat + '_r.jpg'), quality=88)
        mm = float((metal * float(mt.get('metal', 1))).mean()); mtl = 1.0 if mm > 0.5 else round(mm, 2)
        lib[nid] = {'tex': mat, 'mode': 'abs', 'mpt': 1.0, 'rough': 0.3 if leaf else 0.5, 'metal': mtl, 'nstr': 1.0, 'spec': 0.9, 'relief': 0.35, 'macro': 0, 'scan': 1, **({'leaf': 1, 'detile': -1} if leaf else {})}
        named[mat] = [nid, '#ffffff']; rows.append((mat, nid)); nid += 1
js = ('// LUMIERE v14 - generated by tools/textures/scans.py from tools/blender/scans14.py (CC0 Poly Haven scans: tools/polyhaven/SOURCES.md).\n'
      '// The scanned props\' materials: library entries from id 48 up (their textures are www/tex/<name>_a/_n/_r.jpg) and the names the GLBs use.\n'
      f'export const SCAN_LIB = {json.dumps({str(k): v for k, v in lib.items()}, separators=(", ", ": "))};\n'
      f'export const SCAN_NAMED = {json.dumps(named, separators=(", ", ": "))};\n')
open(os.path.join(www, 'js', 'scans.js'), 'w').write(js)
for r in rows: print('SCANTEX', *r)
print('SCANTEX ids', 48, '..', nid - 1)
